// Build-time codegen for the /articles/<slug> perf fix (#7149).
//
// Why: data/albumArticles/<drummer>.js stays the single source of truth (rule 1
// — one data module per domain), organized per-drummer for content authoring
// (see CLAUDE.md's "Data Modules" section). But the frontend bundle's only way
// to reach any single article was `import('./data/albumArticles')`, which pulls
// in every one of the ~429 articles (~10MB raw / 2.5MB transfer) before a single
// paragraph can render — a 26s LCP on simulated slow 4G for every album article,
// every time (#5588 already fixed every *other* route; this was the last one).
//
// This script generates, per article slug, a standalone module the frontend can
// dynamically import() on its own — plus a lightweight metadata manifest (no
// article bodies) for the listing/rail UIs that need to enumerate all articles
// without paying for any of their content. Node-side consumers (api/sitemap.js,
// api/meta/[...path].js, llms generators) keep importing the full barrel
// (data/albumArticles/index.js) directly and are unaffected.
//
// Runs as part of scripts/build.sh; output is committed (same pattern as
// public/llms/**) so `expo start --web` also works without a build step.

import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import fs from 'node:fs';
import { ALBUM_ARTICLES } from '../packages/frontend/data/albumArticles/index.js';

const __dirname = dirname(fileURLToPath(import.meta.url));
const OUT_DIR = join(__dirname, '..', 'packages', 'frontend', 'data', 'albumArticles', 'generated');
const GENERATED_HEADER = (source) =>
  `// Auto-generated by scripts/generate-album-article-chunks.mjs from\n// ${source} — do not edit directly.\n`;

// Small, listing/gating-only metadata. Every field here must stay cheap (a few
// bytes to a couple hundred) — the whole point of the manifest is that it can
// be preloaded on the homepage rail / drummer-profile "related articles" /
// /articles index without paying for any article's ~2-3KB+ body content.
const MANIFEST_FIELDS = [
  'slug', 'title', 'description', 'articleType', 'drummer', 'drummerId',
  'relatedDrummerSlug', 'relatedDrummers', 'band', 'bands', 'albumTitle',
  'artist', 'year', 'genre', 'country', 'ogImage', 'isAlbumArticle',
  'author', 'producer', 'label', 'studio', 'datePublished', 'dateModified',
];

function buildManifestEntry(article) {
  const entry = {};
  for (const field of MANIFEST_FIELDS) {
    if (article[field] !== undefined) entry[field] = article[field];
  }
  return entry;
}

fs.mkdirSync(OUT_DIR, { recursive: true });

const slugs = Object.keys(ALBUM_ARTICLES);
const currentFiles = new Set(slugs.map((slug) => `${slug}.js`));
currentFiles.add('albumArticlesManifest.js');
currentFiles.add('albumArticlesLoaders.js');

// Remove stale per-slug files for articles that no longer exist so this
// directory can never silently drift ahead of data/albumArticles/index.js.
for (const file of fs.readdirSync(OUT_DIR)) {
  if (!file.endsWith('.js')) continue;
  if (!currentFiles.has(file)) fs.unlinkSync(join(OUT_DIR, file));
}

let written = 0;
for (const slug of slugs) {
  const article = ALBUM_ARTICLES[slug];
  const body = `${GENERATED_HEADER('packages/frontend/data/albumArticles/index.js')}export default ${JSON.stringify(article, null, 2)};\n`;
  fs.writeFileSync(join(OUT_DIR, `${slug}.js`), body);
  written++;
}

const manifest = slugs.map((slug) => buildManifestEntry(ALBUM_ARTICLES[slug]));
const manifestBody =
  `${GENERATED_HEADER('packages/frontend/data/albumArticles/index.js')}` +
  `// Lightweight per-article metadata (no bodies) for listings/rails/gating —\n` +
  `// see App.js preloadAlbumArticlesIndex(). Full article content lives in the\n` +
  `// per-slug modules loaded via albumArticlesLoaders.js.\n` +
  `export const ALBUM_ARTICLES_MANIFEST = ${JSON.stringify(manifest, null, 2)};\n`;
fs.writeFileSync(join(OUT_DIR, 'albumArticlesManifest.js'), manifestBody);

const loaderLines = slugs.map((slug) => `  ${JSON.stringify(slug)}: () => import('./${slug}.js'),`).join('\n');
const loadersBody =
  `${GENERATED_HEADER('packages/frontend/data/albumArticles/index.js')}` +
  `// One dynamic import() per article slug, so a single /articles/<slug> page\n` +
  `// fetches only its own module instead of the whole albumArticles dataset.\n` +
  `const loaders = {\n${loaderLines}\n};\n\n` +
  `export function loadAlbumArticle(slug) {\n` +
  `  const loader = loaders[slug];\n` +
  `  return loader ? loader().then((m) => m.default) : Promise.resolve(null);\n` +
  `}\n`;
fs.writeFileSync(join(OUT_DIR, 'albumArticlesLoaders.js'), loadersBody);

console.log(`[generate-album-article-chunks] wrote ${written} per-slug modules + manifest (${manifest.length} entries) + loaders to ${OUT_DIR}`);
