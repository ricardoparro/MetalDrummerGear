// Generator for issue #7149 (L4 perf: /articles/<slug> LCP 26s on mobile).
//
// Every album drum-setup article used to live in one ~10MB browser chunk
// (data/albumArticles/index.js, composed from all per-drummer modules) and
// TopListPage downloaded the whole thing before it could render a single
// article. This script scans the per-drummer modules and writes a small,
// browser-safe catalog:
//   - ALBUM_ARTICLES_META: slug -> lightweight fields only (no article body),
//     for related-article rails and list pages.
//   - ALBUM_ARTICLE_LOADERS: moduleFile -> () => import('./<moduleFile>.js'),
//     one dynamic-import per per-drummer module, so a single article page
//     only downloads its own chunk.
//
// Node/API consumers (api/sitemap.js, api/meta/[...path].js, the llms
// generators) are untouched — they still import the full
// packages/frontend/data/albumArticles.js barrel synchronously.
//
// Regenerated automatically by `bash scripts/build.sh`. The output is also
// committed so `expo start` dev servers have it without a build step; re-run
// this script directly after adding/editing an album article if you need the
// catalog to reflect the change before the next full build.
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

const REPO_ROOT = path.resolve(import.meta.dirname, '..');
const ARTICLES_DIR = path.join(REPO_ROOT, 'packages/frontend/data/albumArticles');
const OUT_FILE = path.join(ARTICLES_DIR, 'albumArticlesCatalog.js');

// Only scalar/short fields — never the long-form body content (intro,
// drumKit, cymbals, hardware, recordingTechniques, trackAnalysis, faq, etc.)
// that makes the per-drummer modules heavy.
const LIGHT_FIELDS = [
  'slug', 'albumTitle', 'artist', 'drummer', 'drummerId', 'relatedDrummerSlug',
  'relatedDrummers', 'year', 'genre', 'title', 'description', 'ogImage',
  'datePublished', 'dateModified', 'isAlbumArticle',
];

const files = fs.readdirSync(ARTICLES_DIR)
  .filter((f) => f.endsWith('.js') && f !== 'index.js' && f !== path.basename(OUT_FILE))
  .sort();

const meta = {};
for (const file of files) {
  const moduleFile = file.slice(0, -3);
  const mod = await import(pathToFileURL(path.join(ARTICLES_DIR, file)).href);
  const articles = mod.articles || mod.default || {};
  for (const [slug, article] of Object.entries(articles)) {
    const entry = { moduleFile };
    for (const field of LIGHT_FIELDS) {
      if (article[field] !== undefined) entry[field] = article[field];
    }
    meta[slug] = entry;
  }
}

const loaderLines = files
  .map((f) => f.slice(0, -3))
  .map((moduleFile) => `  '${moduleFile}': () => import('./${moduleFile}.js'),`)
  .join('\n');

const out = `// AUTO-GENERATED by scripts/generate-album-articles-catalog.mjs — do not hand-edit.
// See that script for why this file exists (issue #7149).

export const ALBUM_ARTICLES_META = ${JSON.stringify(meta, null, 2)};

export const ALBUM_ARTICLE_LOADERS = {
${loaderLines}
};
`;

fs.writeFileSync(OUT_FILE, out);
console.log(`Wrote ${path.relative(REPO_ROOT, OUT_FILE)}: ${Object.keys(meta).length} articles across ${files.length} modules.`);
