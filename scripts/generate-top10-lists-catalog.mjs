// Generator for issue #9106 (L4 perf: /lists/<slug> LCP ~13s on mobile,
// chronically slow since the 2026-07-15 baseline).
//
// data/top10Lists.js is one ~860KB module covering all 97 top-10 lists
// (rankings, FAQ, intro/conclusion prose for every entry). TopListPage
// blocked its ENTIRE render behind that single module — a bare spinner
// until the whole thing downloaded and parsed, even though the header
// (title/description) only needs a few scalar fields. This script writes a
// small, browser-safe catalog of just those fields so TopListPage can paint
// the header as soon as the catalog resolves, then fill in rankings/FAQ
// when the full module arrives in the background. Mirrors the
// albumArticlesCatalog pattern from issue #7149.
//
// Regenerated automatically by `bash scripts/build.sh`. The output is also
// committed so `expo start` dev servers have it without a build step; re-run
// this script directly after editing data/top10Lists.js if you need the
// catalog to reflect the change before the next full build.
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

const REPO_ROOT = path.resolve(import.meta.dirname, '..');
const DATA_FILE = path.join(REPO_ROOT, 'packages/frontend/data/top10Lists.js');
const OUT_FILE = path.join(REPO_ROOT, 'packages/frontend/data/top10ListsCatalog.js');

// Only scalar/short fields — never rankings/faq/intro/conclusion/relatedLists,
// which make up the bulk of the module's weight.
const LIGHT_FIELDS = [
  'slug', 'title', 'description', 'seoDescription', 'emoji', 'isArticle',
  'ogImage', 'datePublished', 'dateModified', 'author',
];

const mod = await import(pathToFileURL(DATA_FILE).href);
const lists = mod.getAllTop10Lists ? mod.getAllTop10Lists() : Object.values(mod.TOP_10_LISTS || {});

const meta = {};
for (const list of lists) {
  const entry = {};
  for (const field of LIGHT_FIELDS) {
    if (list[field] !== undefined) entry[field] = list[field];
  }
  meta[list.slug] = entry;
}

const out = `// AUTO-GENERATED by scripts/generate-top10-lists-catalog.mjs — do not hand-edit.
// See that script for why this file exists (issue #9106).

export const TOP10_LISTS_META = ${JSON.stringify(meta, null, 2)};
`;

fs.writeFileSync(OUT_FILE, out);
console.log(`Wrote ${path.relative(REPO_ROOT, OUT_FILE)}: ${Object.keys(meta).length} lists.`);
